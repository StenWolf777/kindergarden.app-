function getLang() {
  try { return localStorage.getItem('bogcha_lang') || 'uz'; } catch (e) { return 'uz'; }
}

function setLang(lang) {
  try { localStorage.setItem('bogcha_lang', lang); } catch (e) {}
}

function t(key, vars) {
  const lang = getLang();
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.uz;
  let text = dict[key];
  if (text === undefined) text = (TRANSLATIONS.uz[key] !== undefined) ? TRANSLATIONS.uz[key] : key;
  if (vars) {
    Object.keys(vars).forEach(k => { text = text.split(`{${k}}`).join(vars[k]); });
  }
  return text;
}

function applyTranslations(root) {
  root = root || document;
  root.querySelectorAll('[data-i18n]').forEach(el => {
    const html = el.getAttribute('data-i18n-html');
    const value = t(el.getAttribute('data-i18n'));
    if (html === 'true') el.innerHTML = value; else el.textContent = value;
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
  root.querySelectorAll('[data-i18n-title]').forEach(el => {
    const value = t(el.getAttribute('data-i18n-title'));
    el.setAttribute('title', value);
    if (el.hasAttribute('aria-label')) el.setAttribute('aria-label', value);
  });
  const html = document.documentElement;
  if (html) html.setAttribute('lang', getLang());
}
